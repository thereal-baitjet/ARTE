/** Bind pgTAP seed assertions to the checked-in, rights-verified release manifest.
 * Run after scripts/build-catalog-manifest.mjs; --check rejects stale generated SQL in CI.
 */
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG_PROVIDERS } from "./build-catalog-manifest.mjs";

const manifestUrl = new URL("../lib/artworks/data/catalog-manifest.json", import.meta.url);
const outputUrl = new URL("../supabase/tests/database/catalog.test.sql", import.meta.url);
export function generateDatabaseCatalogTest(manifest) {
assert.ok(Array.isArray(manifest.artworks) && manifest.artworks.length > 0, "manifest.artworks must contain the verified catalog");
assert.equal(manifest.artworks.length, manifest.realArtworkCount, "manifest real count must match its exact identities");
assert.equal(manifest.totalArtworkCount, manifest.realArtworkCount + manifest.syntheticFixtureCount, "manifest total must include synthetic fixtures");

const records = [...manifest.artworks].sort((left, right) => String(left.id).localeCompare(String(right.id)));
assert.equal(new Set(records.map((record) => record.id)).size, records.length, "manifest artwork IDs must be unique");
assert.equal(new Set(records.map((record) => `${record.source}:${record.objectId}`)).size, records.length, "manifest source-qualified object IDs must be unique");
for (const record of records) {
  assert.match(record.id, /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i, "manifest artwork ID must be a UUID");
  assert.ok(Number.isSafeInteger(record.objectId) && record.objectId > 0, "manifest source ID must be a positive integer");
  assert.ok(Object.hasOwn(CATALOG_PROVIDERS, record.source), "manifest source must be a supported museum");
  for (const field of ["sourceName", "museumSlug", "sourceUrl", "imagePath"]) assert.ok(typeof record[field] === "string" && record[field].length > 0, `manifest ${field} is required`);
  assert.ok(Number.isSafeInteger(record.width) && record.width > 0 && Number.isSafeInteger(record.height) && record.height > 0, "manifest dimensions must be positive integers");
  assert.equal(record.license, CATALOG_PROVIDERS[record.source].license, "manifest image license must match the verified provider image rights");
  assert.equal(record.rightsState, "public_domain", "manifest release images must be public domain");
}

const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const expected = records.map((record) => `  (${quote(record.id)}::uuid, ${[record.sourceName, record.objectId, record.museumSlug, record.sourceUrl, record.imagePath, record.license].map(quote).join(", ")}, ${record.width}, ${record.height})`).join(",\n");
const sql = `-- Generated by scripts/generate-database-catalog-test.mjs from catalog-manifest.json.
-- Exact identities protect against both missing seed rows and unintended additions.
begin;
create extension if not exists pgtap with schema extensions;
select plan(6);

create temporary table expected_release_catalog (
  artwork_id uuid primary key,
  source_name text not null,
  source_artwork_id text not null,
  museum_slug text not null,
  source_url text not null,
  image_path text not null,
  image_license text not null,
  image_width int not null,
  image_height int not null,
  unique (source_name, source_artwork_id)
) on commit drop;
insert into expected_release_catalog (artwork_id, source_name, source_artwork_id, museum_slug, source_url, image_path, image_license, image_width, image_height) values
${expected};

select results_eq(
  $$select id, source_name, source_artwork_id from public.artworks where not is_synthetic order by id$$,
  $$select artwork_id, source_name, source_artwork_id from expected_release_catalog order by artwork_id$$,
  'real seed artwork identities match the complete verified release manifest'
);

select results_eq(
  $$select count(*)::bigint from public.artworks$$,
  $$values (${manifest.totalArtworkCount}::bigint)$$,
  'seed total matches the generated release manifest including synthetic test fixtures'
);

select results_eq(
  $$select count(*)::bigint from public.artworks where is_synthetic$$,
  $$values (${manifest.syntheticFixtureCount}::bigint)$$,
  'synthetic fixture count matches the release manifest and remains distinct from real inventory'
);

select results_eq(
  $$select s.artwork_id, s.source_name, s.source_artwork_id, s.source_url from public.artwork_sources s
    join public.artworks a on a.id = s.artwork_id
    where not a.is_synthetic
    order by s.artwork_id$$,
  $$select artwork_id, source_name, source_artwork_id, source_url from expected_release_catalog order by artwork_id$$,
  'every released museum identity has exactly one matching authoritative source record'
);

select results_eq(
  $$select a.id from public.artworks a join public.museums m on m.id = a.museum_id
    join expected_release_catalog e on e.artwork_id = a.id
    where not a.is_synthetic and a.is_published
      and a.image_rights_state = 'public_domain' and a.image_license = e.image_license
      and m.slug = e.museum_slug and a.source_name = e.source_name
      and a.source_url = e.source_url and a.commercial_usage_allowed
    order by a.id$$,
  $$select artwork_id from expected_release_catalog order by artwork_id$$,
  'every real seed record is publishable, individually licensed, and linked to the correct museum source'
);

select results_eq(
  $$select i.artwork_id from public.artwork_images i join public.artworks a on a.id = i.artwork_id
    join expected_release_catalog e on e.artwork_id = a.id
    where not a.is_synthetic
      and i.url = e.image_path
      and i.width = e.image_width and i.height = e.image_height and length(i.alt_text) > 0
      and i.license = e.image_license and length(i.rights_holder) > 0
      and i.source_url = e.source_url and i.commercial_usage_allowed
    order by i.artwork_id$$,
  $$select artwork_id from expected_release_catalog order by artwork_id$$,
  'every real seed image has the correct local derivative, dimensions, attribution, and source'
);

select * from finish();
rollback;
`;
return sql;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
const manifest = JSON.parse(await readFile(manifestUrl, "utf8"));
const sql = generateDatabaseCatalogTest(manifest);
if (process.argv.includes("--check")) {
  assert.equal(await readFile(outputUrl, "utf8"), sql, "catalog.test.sql is stale; run node scripts/generate-database-catalog-test.mjs");
  console.log(`Database catalog expectations match all ${manifest.realArtworkCount} real manifest identities`);
} else {
  await writeFile(outputUrl, sql);
  console.log(`Generated database catalog assertions for ${manifest.realArtworkCount} verified museum artworks`);
}
}
